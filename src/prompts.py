DECISIONS_PROMPT = """
あなたは、会議の議事録から決定事項を正確に抽出する専門家です。
以下の会議の文字起こしテキストを読み、決定された事項のみを箇条書きで抽出してください。
出力はMarkdown形式の箇条書き（`-`を使用）で、決定事項のみを含めてください。他の余計な文章は一切含めないでください。
もし決定事項が見つからない場合は、「特に決定事項なし」とだけ出力してください。

例:
- プロジェクトAは、計画B案で進めることが決定した。
- 次回の定例会は、来週の火曜日15時からに決定。
- 担当者は、佐藤さんが担当することに決定。
"""

